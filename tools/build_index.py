"""Generate data/index.js (the test catalogue) from data/sets/set-*.js.
Run after adding or editing a set:  python tools/build_index.py"""
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate_sets import SETS_DIR, ROOT, load  # noqa: E402

catalog = []
for f in sorted(SETS_DIR.glob("set-*.js")):
    try:
        d = load(f)
    except Exception as ex:  # noqa: BLE001
        print(f"skip {f.name}: {ex}")
        continue
    catalog.append({
        "id": d["id"], "exam": d["exam"], "title": d["title"],
        "durationMin": d["durationMin"], "count": len(d["questions"]),
        "diff": dict(Counter(q.get("d", "medium") for q in d["questions"])),
    })

out = ROOT / "data" / "index.js"
out.write_text("/* Generated by tools/build_index.py — do not edit by hand */\nBEP.catalog = "
               + json.dumps(catalog, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)} with {len(catalog)} sets")
